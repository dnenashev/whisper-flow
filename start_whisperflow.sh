#!/bin/bash

# Скрипт для запуска WhisperFlow

# Определяем цвета для вывода
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "\n${BLUE}=== WhisperFlow - Установщик и запуск ===${NC}\n"

# Переходим в директорию проекта
cd "$(dirname "$0")"

# Проверка и установка необходимых разрешений
echo -e "${YELLOW}Проверка необходимых разрешений...${NC}"
echo -e "На macOS для корректной работы программе нужны следующие разрешения:"
echo -e "1. Доступ к микрофону"
echo -e "2. Универсальный доступ (для симуляции нажатий клавиш)"

echo -e "\n${YELLOW}Проверка наличия зависимостей...${NC}"
# Проверяем, активировано ли виртуальное окружение
if [ ! -d "venv" ]; then
    echo -e "${RED}Виртуальное окружение не найдено.${NC}"
    echo -e "Создаю виртуальное окружение и устанавливаю зависимости..."
    python3 -m venv venv
    source venv/bin/activate
    pip install -r requirements.txt
    pip install numpy
else
    echo -e "${GREEN}Виртуальное окружение найдено.${NC}"
    source venv/bin/activate
fi

# Запрос разрешения на доступ к микрофону
echo -e "\n${YELLOW}Проверка разрешения на доступ к микрофону...${NC}"
read -p "Разрешить доступ к микрофону? (y/n): " allow_mic
if [ "$allow_mic" == "y" ]; then
    # На macOS это просто запросит разрешение при первом использовании
    echo -e "${GREEN}Доступ к микрофону будет запрошен при первом использовании.${NC}"
fi

echo -e "\n${YELLOW}ВАЖНО: Для работы программы нужно разрешение на 'Универсальный доступ'${NC}"
echo -e "Сейчас откроется окно 'Системные настройки > Конфиденциальность и безопасность > Универсальный доступ'"
echo -e "Необходимо добавить терминал в список разрешенных приложений."
echo -e "1. Нажмите на значок замка в нижнем левом углу"
echo -e "2. Введите пароль администратора"
echo -e "3. Нажмите + и добавьте приложение Terminal.app или iTerm.app"
echo -e "4. Поставьте галочку рядом с добавленным приложением"

read -p "Открыть системные настройки сейчас? (y/n): " open_settings
if [ "$open_settings" == "y" ]; then
    open "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility"
    echo -e "${YELLOW}После настройки разрешений вернитесь в терминал и нажмите Enter для продолжения${NC}"
    read -p "Нажмите Enter для продолжения..."
fi

echo -e "\n${GREEN}Запускаю WhisperFlow...${NC}"
echo -e "Программа будет работать в фоновом режиме."
echo -e "${YELLOW}Использование:${NC}"
echo -e "1. Нажмите и удерживайте Shift+Пробел для начала записи"
echo -e "2. Говорите, пока удерживаете клавиши"
echo -e "3. Отпустите клавиши для завершения записи и транскрипции"
echo -e "4. Если текст не вставляется автоматически:"
echo -e "   - Проверьте файл ~/whisperflow_transcript.txt"
echo -e "   - Используйте Command+V для вставки"
echo -e "   - Скопируйте текст из консоли\n"

# Запускаем программу БЕЗ прав администратора
# Это должно решить проблему с буфером обмена
python whisper-flow.py 